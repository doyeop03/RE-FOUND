const AS_OF = "2026.11.10";
const MONTHS = ["6월", "7월", "8월", "9월", "10월", "11월"];

/** 호가 범위를 받아 6개월치 추이를 결정적으로 만든다 (랜덤 사용 안 함) */
function market(
  low: number,
  high: number,
  listings: number,
  drift: number[],
): MarketData {
  const mid = (low + high) / 2;
  const round = (n: number) => Math.round(n / 1000) * 1000;
  return {
    low,
    high,
    listings,
    asOf: AS_OF,
    trend: MONTHS.map((month, i) => {
      const k = drift[i];
      return {
        month,
        low: round(low * k),
        median: round(mid * k),
        high: round(high * k),
      };
    }),
  };
}

